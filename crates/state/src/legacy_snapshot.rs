//! Frozen bincode v1 wire layout for ChainState snapshots.
//! Keep field order and field types identical to the historical ChainState.
//! When ChainState evolves, update only the conversion defaults, never this layout.

use super::*;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct LegacyChainStateV1 {
    pub height:u64,
    pub last_block_hash:Hash,
    pub accounts:BTreeMap<Address,Account>,
    pub validators:BTreeMap<Hash,Validator>,
    #[serde(default)] pub unbonding:BTreeMap<Hash,UnbondingEntry>,
    pub nodes:BTreeMap<Hash,Node>,
    pub contributions:BTreeMap<Hash,Contribution>,
    pub rewards:BTreeMap<Hash,Reward>,
    pub purchases:BTreeMap<Hash,Purchase>,
    pub billing:BTreeMap<Hash,BillingRecord>,
    pub tickets:BTreeMap<Hash,Ticket>,
    pub draws:BTreeMap<Hash,DrawState>,
    pub draw_results:BTreeMap<Hash,DrawResult>,
    #[serde(rename="cu_fund_native_units",alias="cu_fund_mfdm")] pub cu_fund_native_units:u128,
    #[serde(rename="annual_reserve_native_units",alias="annual_reserve_mfdm")] pub annual_reserve_native_units:u128,
    #[serde(rename="draw_prize_pool_native_units",alias="draw_prize_pool_mfdm")] pub draw_prize_pool_native_units:u128,
    pub events:Vec<Event>,
    pub ledger:Vec<LedgerEntry>,
    pub supply:Supply,
    pub epoch:u64,
    pub epoch_length:u64,
    pub active_validator_set:BTreeMap<Hash,freedom_types::ValidatorSetEntry>,
    #[serde(default)] pub asset_registry:BTreeMap<Hash,AssetDefinition>,
    #[serde(default)] pub cross_chain_asset_registries:BTreeMap<Hash,freedom_types::CrossChainAssetRegistry>,
    #[serde(default)] pub processed_bridge_messages:BTreeMap<Hash,BridgeMessage>,
    #[serde(default)] pub bridge_message_status:BTreeMap<Hash,BridgeMessageStatus>,
    #[serde(default)] pub bridge_message_approval_sets:BTreeMap<Hash,freedom_types::BridgeMessageApprovalSet>,
    #[serde(default)] pub bridge_message_approval_epochs:BTreeMap<Hash,u64>,
    #[serde(default)] pub bridge_withdrawals:BTreeMap<Hash,BridgeWithdrawal>,
    #[serde(default)] pub bridge_withdrawal_status:BTreeMap<Hash,BridgeWithdrawalStatus>,
    #[serde(default)] pub bridge_accounting:BTreeMap<Hash,BridgeAccounting>,
    #[serde(default)] pub bridge_security_policies:BTreeMap<Hash,BridgeSecurityPolicy>,
    #[serde(default)] pub bridge_approval_sets:BTreeMap<Hash,BridgeApprovalSet>,
    #[serde(default)] pub bridge_pause_authorizations:BTreeMap<Hash,BridgePauseAuthorizationSet>,
    #[serde(default)] pub bridge_nonce_registry:BTreeMap<Hash,BTreeSet<u64>>,
    #[serde(default)] pub bridge_rate_limits:BTreeMap<Hash,BridgeRateLimitUsage>,
    #[serde(default)] pub bridge_deposit_replays:BTreeMap<Hash,DepositReplayRecord>,
    #[serde(default)] pub bridge_mint_authorizations:BTreeMap<Hash,BridgeMintAuthorization>,
    #[serde(default)] pub bridge_withdrawal_rate_limit_period:BTreeMap<Hash,u64>,
    #[serde(default)] pub bitcoin_checkpoints:BTreeMap<Hash,BitcoinChainCheckpoint>,
    #[serde(default)] pub bitcoin_canonical_tips:BTreeMap<Hash,BitcoinChainCheckpoint>,
    #[serde(default)] pub bitcoin_reorg_evidence:BTreeMap<Hash,Vec<BitcoinReorgEvidence>>,
    #[serde(default)] pub bitcoin_reorg_policy:BTreeMap<Hash,freedom_types::BitcoinReorgPolicy>,
    #[serde(default)] pub bitcoin_reorg_recovery:BTreeMap<Hash,freedom_types::BitcoinReorgRecovery>,
    #[serde(default)] pub bitcoin_utxo_attestations:BTreeMap<Hash,freedom_types::BitcoinUtxoCommitmentAttestation>,
    #[serde(default)] pub bitcoin_utxo_attestation_policy_hashes:BTreeMap<Hash,Hash>,
    #[serde(default)] pub bitcoin_utxo_commitments:BTreeMap<Hash,freedom_types::BitcoinUtxoBlockCommitment>,
    #[serde(default)] pub pending_validator_set:BTreeMap<Hash,freedom_types::ValidatorSetEntry>,
    #[serde(default)] pub validator_set_history:BTreeMap<u64,Hash>,
    #[serde(default)] pub validator_set_history_sets:BTreeMap<u64,BTreeMap<Hash,[u8;32]>>,
    #[serde(default)] pub validator_set_history_entries:BTreeMap<u64,BTreeMap<Hash,freedom_types::ValidatorSetEntry>>,
    #[serde(default)] pub validator_set_history_key_hashes:BTreeMap<u64,Hash>,
    #[serde(default)] pub validator_set_certificate:Option<freedom_types::ValidatorSetCertificate>,
    #[serde(default)] pub staking_activated:bool,
    pub epoch_issuance:u128,
    pub epoch_cap:u128,
    pub evidence:BTreeMap<Hash,freedom_types::EquivocationEvidence>,
    pub slashed_evidence:BTreeMap<Hash,u128>
}

